// LUODA 3.1.24 - AI meeting minutes service.
//
// Turns a meeting group's chat history into structured meeting minutes:
//   1. Load text messages from the meeting conversation.
//   2. Build a compact transcript.
//   3. Ask the active AI text profile to summarise into structured minutes.
//      Falls back to a local rule-based digest when no AI profile is
//      configured or the call fails, so the feature always works offline.

